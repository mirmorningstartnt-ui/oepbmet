    </div>
  <?php endif; ?>

  <div class="adm-card">
    <h2>Server requirements</h2>
    <p class="adm-sub">Everything below must pass before installing.</p>
    <table class="adm-table">
      <?php foreach ($checks as $label => $ok): ?>
        <tr><td><?php echo $ok ? '✅' : '❌'; ?></td><td><?php echo htmlspecialchars($label); ?></td><td><?php echo $ok ? 'OK' : 'MISSING'; ?></td></tr>
      <?php endforeach; ?>
    </table>
  </div>

  <?php if ($errors): ?>
    <div class="alert alert-err"><?php foreach ($errors as $e) echo htmlspecialchars($e) . '<br>'; ?></div>
  <?php endif; ?>

  <form method="post" action="install.php" novalidate>
    <div class="adm-card">
      <h2>1 · Database connection</h2>
      <p class="adm-sub">Create the database first in cPanel → MySQL Databases, then enter its name, user and password here (on Hostinger the host is usually <code>localhost</code>).</p>
      <div class="form-grid">
        <div class="form-group"><label class="form-label">Driver</label>
          <select class="form-control" name="driver">
            <option value="mysql" <?php echo $in['driver'] === 'mysql' ? 'selected' : ''; ?>>MySQL / MariaDB (recommended)</option>
            <option value="sqlite" <?php echo $in['driver'] === 'sqlite' ? 'selected' : ''; ?>>SQLite (local testing only)</option>
          </select></div>
        <div class="form-group"><label class="form-label">DB Host</label>
          <input class="form-control" name="host" value="<?php echo htmlspecialchars($in['host']); ?>" /></div>
