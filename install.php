        <div class="form-group"><label class="form-label">DB User</label>
          <input class="form-control" name="user" value="<?php echo htmlspecialchars($in['user']); ?>" placeholder="u123456788_admin" /></div>
        <div class="form-group"><label class="form-label">DB Password</label>
          <input class="form-control" type="password" name="pass" value="" autocomplete="new-password" /></div>
      </div>
    </div>

    <div class="adm-card">
