<?php
/**
 * BMET EC Card Manager — one-time installer.
 * Connects the MySQL database, creates the tables and the admin credentials,
 * then writes admin/includes/config.php.
 *
 * Upload the whole project to cPanel (public_html), open  /install.php  once,
 * fill the form, and DELETE THIS FILE after a successful installation.
 */
error_reporting(E_ALL);
ini_set('display_errors', '1');
date_default_timezone_set('UTC');

$root = __DIR__;
$config_file = $root . '/admin/includes/config.php';
$installed = is_file($config_file);

$errors = [];
$done = false;
$in = [
    'driver' => 'mysql', 'host' => 'localhost', 'port' => '3306',
    'name' => '', 'user' => '', 'pass' => '',
    'admin_user' => 'admin', 'admin_email' => '', 'admin_pass' => '', 'admin_pass2' => '',
    'base_url' => '',
];

$checks = [
    'PHP 7.4+' => version_compare(PHP_VERSION, '7.4.0', '>='),
    'PDO extension' => extension_loaded('pdo'),
    'PDO MySQL driver' => extension_loaded('pdo_mysql'),
    'GD extension (photo handling)' => extension_loaded('gd'),
    'admin/includes writable' => is_writable($root . '/admin/includes'),
    'project root writable' => is_writable($root),
];

if ($_SERVER['REQUEST_METHOD'] === 'POST') {
    foreach ($in as $k => $_v) if (isset($_POST[$k])) $in[$k] = trim((string)$_POST[$k]);

    if ($in['driver'] === 'mysql' && $in['name'] === '') $errors[] = 'Database name is required.';
    if ($in['driver'] === 'mysql' && $in['user'] === '') $errors[] = 'Database user is required.';
    if ($in['admin_user'] === '') $errors[] = 'Admin username is required.';
    if (strlen($in['admin_pass']) < 6) $errors[] = 'Admin password must be at least 6 characters.';
    if ($in['admin_pass'] !== $in['admin_pass2']) $errors[] = 'Admin passwords do not match.';

    if (!$errors) {
        try {
            if ($in['driver'] === 'sqlite') {
                $dir = $root . '/admin/data';
                if (!is_dir($dir)) mkdir($dir, 0775, true);
                $pdo = new PDO('sqlite:' . $dir . '/app.sqlite');
                $pdo->setAttribute(PDO::ATTR_ERRMODE, PDO::ERRMODE_EXCEPTION);
            } else {
                $dsn = sprintf('mysql:host=%s;port=%d;dbname=%s;charset=utf8mb4', $in['host'], (int)$in['port'], $in['name']);
                $pdo = new PDO($dsn, $in['user'], $in['pass'], [PDO::ATTR_ERRMODE => PDO::ERRMODE_EXCEPTION]);
            }
            require_once $root . '/admin/includes/db.php';
            foreach (ec_schema_sql($in['driver']) as $sql) $pdo->exec($sql);

            // admin account
            $st = $pdo->prepare('SELECT id FROM admins WHERE username = ?');
            $st->execute([$in['admin_user']]);
            $hash = password_hash($in['admin_pass'], PASSWORD_DEFAULT);
            if ($st->fetch()) {
                $pdo->prepare('UPDATE admins SET password_hash = ?, email = ? WHERE username = ?')
                    ->execute([$hash, $in['admin_email'], $in['admin_user']]);
            } else {
                $pdo->prepare('INSERT INTO admins (username, email, password_hash) VALUES (?, ?, ?)')
                    ->execute([$in['admin_user'], $in['admin_email'], $hash]);
            }

            // base url
            $base = $in['base_url'];
            if ($base === '') {
                $scheme = (!empty($_SERVER['HTTPS']) && $_SERVER['HTTPS'] !== 'off') ? 'https' : 'http';
                $base = $scheme . '://' . ($_SERVER['HTTP_HOST'] ?? 'localhost');
                $dir = str_replace('\\', '/', dirname($_SERVER['SCRIPT_NAME'] ?? '/install.php'));
                $base .= rtrim($dir, '/');
            }
            $base = rtrim($base, '/');

            $cfg = [
                'driver' => $in['driver'],
                'host' => $in['host'],
                'port' => (int)$in['port'],
                'name' => $in['name'],
                'user' => $in['user'],
                'pass' => $in['pass'],
                'base_url' => $base,
                'installed_at' => date('c'),
            ];
            if ($in['driver'] === 'sqlite') $cfg['sqlite_path'] = $root . '/admin/data/app.sqlite';
            $php = "<?php\n/* Generated by install.php on " . date('c') . " — do not edit by hand unless you know what you are doing. */\nreturn " . var_export($cfg, true) . ";\n";
            if (@file_put_contents($config_file, $php) === false) throw new Exception('Could not write ' . $config_file);
            @chmod($config_file, 0644);

            @mkdir($root . '/ec-card/uploads', 0775, true);
            @mkdir($root . '/ec-card/verify', 0775, true);
            @mkdir($root . '/ec-card/enrollment-card', 0775, true);

            $done = true;
        } catch (Exception $e) {
            $errors[] = 'Installation failed: ' . $e->getMessage();
        }
    }
}
